const opt = (label: string) => ({ value: label, label });

const ready = (score: number, text: string) => ({ value: String(score), label: `${score} = ${text}` });

function anchors(texts: [string, string, string, string, string]) {
  return texts.map((text, index) => ({ score: index + 1, text }));
}

