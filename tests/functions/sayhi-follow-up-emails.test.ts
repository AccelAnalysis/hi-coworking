const PREVIEW_FILE = "apps/web/src/lib/sayhiEmailPreviews.generated.ts";
function previewModule(): string {
  return [
    "// Generated by tests/functions/sayhi-follow-up-emails.test.ts from",
    "// apps/functions/src/sayhi/followUpEmails.ts. Do not edit by hand. To refresh:",
    "// UPDATE_SAYHI_EMAIL_PREVIEWS=1 npx vitest run tests/functions/sayhi-follow-up-emails.test.ts",
    "// Sample names and visits are fictional. Only the private preview imports this.",
    "",
    "export type SayHiEmailPreview = { id: string; label: string; trigger: string; subject: string; html: string; text: string };",
    "",
    "// The env check is inlined at build time, so production bundles drop the draft copy.",
    "export const SAYHI_EMAIL_PREVIEWS: SayHiEmailPreview[] =",
    `  process.env.NEXT_PUBLIC_SAYHI_PREVIEW_DEMO === "true" ? ${JSON.stringify(previewSamples(), null, 2)} : [];`,
    "",
  ].join("\n");
}

function memoryStore(user: { email?: string; displayName?: string } | null) {
  const docs = new Map<string, Record<string, unknown>>();
  const store: WelcomeEmailStore = {
    async claim(id, data) {
      const existing = docs.get(id);
      if (existing && (existing.status === "sent" || existing.status === "sending")) return false;
      docs.set(id, { ...data, status: "sending" });
      return true;
    },
    async markSent(id, messageId) { docs.set(id, { ...docs.get(id), status: "sent", messageId }); },
    async markFailed(id, code) { docs.set(id, { ...docs.get(id), status: "failed", errorCode: code }); },
    async loadUser() { return user; },
  };
  return { store, docs };
}

function fakeProvider() {
  const sent: Array<Parameters<EmailProvider["send"]>[0]> = [];
  const provider = { send: vi.fn(async (msg) => { sent.push(msg); return { messageId: `m${sent.length}` }; }) } as unknown as EmailProvider;
  return { provider, sent };
}

