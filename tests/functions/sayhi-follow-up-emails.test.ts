describe("SayHi follow-up email copy", () => {
  const samples = previewSamples();

  it("follows the copy rules", () => {
    for (const sample of samples) {
      for (const body of [sample.subject, sample.html, sample.text]) {
        expect(body).not.toMatch(/stripe/i);
        expect(body).not.toMatch(/\bfree\b/i);
        expect(body).not.toMatch(/Carrollton|Blvd|23314/);
        expect(body).not.toMatch(/Say Hi\b|Sayhi\b/);
        expect(body).not.toMatch(/[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[a-z]{2,}/);
        expect(body).not.toMatch(/\$\d+(\.\d\d)?\s*(\/|per)\s*h/i);
      }
      expect(sample.html).toContain(`src="${EMAIL_LOGO_URL}"`);
      expect(sample.html).toContain("#101D4B");
      expect(sample.html).toContain("font-family:Fraunces");
      expect(sample.html).toContain("font-weight:600");
      expect(sample.html).toContain("'DM Sans'");
      expect(sample.html).toContain(`href="${ORIGIN}/my-hi"`);
      expect(sample.html).toContain(`href="${ORIGIN}/terms#extra-time"`);
      expect(sample.text).toContain(`${ORIGIN}/my-hi`);
      expect(sample.text).toContain(`${ORIGIN}/terms#extra-time`);
      expect(sample.text).toContain("SayHi");
      expect(sample.text).toContain("Early Access");
    }
  });

  it("states the right billing destination and amount in Eastern time", () => {
    const [included, partly, memberCard, card, noCheckout] = samples;
    for (const sample of [included, partly, memberCard, card]) {
      expect(sample.subject).toBe("Extra time from your visit on Tuesday, November 3");
      expect(sample.text).not.toMatch(/next (membership )?bill/i);
    }
    expect(card.subject).toBe(included.subject);
    expect(included.text).toContain("Your booking ended at 5:00 PM, and you checked out at 5:42 PM.");
    expect(included.text).toContain("so this visit has 45 minutes of extra time. All 45 minutes came from your plan's included hours for this month.");
    expect(included.text).toContain("There's no charge for this extra time");
    expect(included.text).not.toMatch(/\$\d/);
    expect(included.text).not.toContain("charged");
    expect(partly.text).toContain("so this visit has 45 minutes of extra time. Of that, 30 minutes came from your plan's included hours for this month, and the other 15 minutes came to $3.50.");
    expect(partly.text).toContain("We've charged $3.50 to the payment method on file for your membership.");
    expect(memberCard.text).toContain("so this visit has 45 minutes of extra time, for $10.50. You had no included plan hours left this month to put toward it.");
    expect(memberCard.text).toContain("We've charged this amount to the payment method on file for your membership.");
    expect(card.text).toContain("30 minutes of extra time, for $8.75.");
    expect(card.text).toContain("card you used for your booking");
    expect(card.text).not.toContain("membership bill");
    expect(noCheckout.subject).toBe("We didn't see you check out on Tuesday, November 3");
    expect(noCheckout.text).toContain("ended at 4:00 PM");
    expect(noCheckout.text).toContain("before any extra time is charged");
  });

  it("handles a visit without a booked end and escapes names", () => {
    const walkIn = renderNoCheckoutEmail({ visitDate: END_4PM, bookedEnd: null, origin: ORIGIN });
    expect(walkIn.text).toContain("Hi there,");
    expect(walkIn.text).not.toContain("one hour after your booking");
    const odd = renderExtraTimeEmail({ billing: "card", firstName: "<b>Al</b>", bookedEnd: END_3PM, checkOutAt: END_3PM, minutes: 75, cents: 2188, origin: ORIGIN });
    expect(odd.html).not.toContain("<b>Al</b>");
    expect(odd.text).toContain("1 hour 15 minutes");
    expect(formatDuration(60)).toBe("1 hour");
  });

  it("keeps the private preview file in sync with the server copy", () => {
    if (process.env.UPDATE_SAYHI_EMAIL_PREVIEWS === "1") writeFileSync(PREVIEW_FILE, previewModule());
    expect(existsSync(PREVIEW_FILE)).toBe(true);
    expect(readFileSync(PREVIEW_FILE, "utf8")).toBe(previewModule());
  });
});

describe("when SayHi follow-up emails send", () => {
  it("picks the extra-time moment and variant", () => {
    const plan = { ...visitBase, overtimeBilling: "plan" };
    expect(extraTimeEmailBilling({ ...visitBase, chargeStatus: "not_charged" }, { ...plan, chargeStatus: "covered_by_plan_hours", overtimeIncludedMinutes: 45, overtimeCents: 0 })).toBe("included");
    expect(extraTimeEmailBilling({ ...plan, chargeStatus: "charging" }, { ...plan, chargeStatus: "charged", overtimeIncludedMinutes: 30, overtimeCents: 350 })).toBe("partly_included");
    expect(extraTimeEmailBilling({ ...plan, chargeStatus: "charging" }, { ...plan, chargeStatus: "charged", overtimeIncludedMinutes: 0 })).toBe("member_card");
    expect(extraTimeEmailBilling({ ...plan, chargeStatus: "charging" }, { ...plan, chargeStatus: "billed_next_invoice" })).toBeNull();
    expect(extraTimeEmailBilling({ ...visitBase, chargeStatus: "charging" }, { ...visitBase, chargeStatus: "charged" })).toBe("card");
    expect(extraTimeEmailBilling({ ...visitBase, chargeStatus: "charging" }, { ...visitBase, overtimeBilling: "guest", chargeStatus: "charged" })).toBe("card");
    expect(extraTimeEmailBilling({ ...visitBase, chargeStatus: "charged" }, { ...visitBase, chargeStatus: "charged" })).toBeNull();
    expect(extraTimeEmailBilling({ ...visitBase, chargeStatus: "charging" }, { ...visitBase, chargeStatus: "charge_failed" })).toBeNull();
    expect(extraTimeEmailBilling({ ...visitBase, chargeStatus: "charging" }, { ...visitBase, chargeStatus: "no_card_on_file" })).toBeNull();
    expect(extraTimeEmailBilling(undefined, { ...visitBase, chargeStatus: "charged", overtimeCents: 0 })).toBeNull();
    expect(isNoCheckoutFlag({ type: "no_checkout", visitId: "v1" })).toBe(true);
    expect(isNoCheckoutFlag({ type: "no_checkin", visitId: "v1" })).toBe(false);
  });

  it("does nothing while the SayHi flag is off", async () => {
    const { provider, sent } = fakeProvider();
    const { store } = memoryStore({ email: "member@example.test" });
    expect(await sendExtraTimeEmail({ visitId: "v1", before: { chargeStatus: "charging" }, after: { ...visitBase, chargeStatus: "charged" } }, { provider, store, env: {} })).toBe("skipped_flag_off");
    expect(await sendExtraTimeEmail({ visitId: "v1", before: { chargeStatus: "charging" }, after: { ...visitBase, chargeStatus: "charged" } }, { provider, store, env: { SAYHI_FLOW_ENABLED: "false" } })).toBe("skipped_flag_off");
    expect(await sendNoCheckoutEmail({ followUp: { type: "no_checkout", visitId: "v1" }, loadVisit: async () => visitBase }, { provider, store, env: {} })).toBe("skipped_flag_off");
    expect(sent).toHaveLength(0);
  });

  it("sends one extra-time email per visit", async () => {
    const { provider, sent } = fakeProvider();
    const { store, docs } = memoryStore({ email: "member@example.test", displayName: "Jordan Lee" });
    const input = { visitId: "v1", before: { ...visitBase, chargeStatus: "charging" }, after: { ...visitBase, overtimeBilling: "plan", overtimeIncludedMinutes: 30, overtimeCents: 350, chargeStatus: "charged" } };
    expect(await sendExtraTimeEmail(input, { provider, store, env: ON, origin: ORIGIN })).toBe("sent");
    expect(await sendExtraTimeEmail(input, { provider, store, env: ON, origin: ORIGIN })).toBe("skipped_already_sent");
    expect(sent).toHaveLength(1);
    expect(sent[0].to).toBe("member@example.test");
    expect(sent[0].text).toContain("Hi Jordan,");
    expect(sent[0].idempotencyKey).toBe("sayhi_extra_time/v1");
    expect(docs.get("sayhi_extra_time_v1")?.status).toBe("sent");
  });

  it("sends one no-check-out email per visit, separate from the extra-time email", async () => {
    const { provider, sent } = fakeProvider();
    const { store, docs } = memoryStore({ email: "member@example.test" });
    const followUp = { type: "no_checkout", visitId: "v1", memberId: "member1" };
    const loadVisit = async () => ({ ...visitBase, status: "auto_closed" });
    expect(await sendNoCheckoutEmail({ followUp, loadVisit }, { provider, store, env: ON, origin: ORIGIN })).toBe("sent");
    expect(await sendNoCheckoutEmail({ followUp, loadVisit }, { provider, store, env: ON, origin: ORIGIN })).toBe("skipped_already_sent");
    expect(await sendNoCheckoutEmail({ followUp: { type: "no_checkin", bookingId: "b1" } as never, loadVisit }, { provider, store, env: ON })).toBe("skipped_not_applicable");
    expect(sent).toHaveLength(1);
    expect(sent[0].subject).toContain("We didn't see you check out");
    expect(docs.has("sayhi_no_checkout_v1")).toBe(true);
  });

  it("never throws and skips without a recipient or key", async () => {
    const { store } = memoryStore({ email: "not-an-email" });
    const failing = { send: async () => { throw new Error("boom"); } } as unknown as EmailProvider;
    const input = { visitId: "v2", before: { chargeStatus: "charging" }, after: { ...visitBase, chargeStatus: "charged" } };
    expect(await sendExtraTimeEmail(input, { provider: failing, store, env: ON })).toBe("skipped_no_recipient");
    expect(await sendExtraTimeEmail(input, { env: ON })).toBe("skipped_no_api_key");
    const ok = memoryStore({ email: "member@example.test" });
    expect(await sendExtraTimeEmail(input, { provider: failing, store: ok.store, env: ON })).toBe("failed");
    expect(ok.docs.get("sayhi_extra_time_v2")?.status).toBe("failed");
  });
});

describe("SayHi follow-up email wiring", () => {
  const triggers = readFileSync("apps/functions/src/sayhi/followUpEmailTriggers.ts", "utf8");
  const module = readFileSync("apps/functions/src/sayhi/followUpEmails.ts", "utf8");

  it("deploys from the mail source with only the email key, and not from the mail workflow", () => {
    const index = readFileSync("firebase/mail-functions/src/index.ts", "utf8");
    expect(index).toContain("sayhi_sendExtraTimeEmail, sayhi_sendNoCheckoutEmail");
    expect(triggers).toContain('document: "kioskVisits/{visitId}", secrets: [resendApiKey]');
    expect(triggers).toContain('document: "staffFollowUps/{followUpId}", secrets: [resendApiKey]');
    const workflow = readFileSync(".github/workflows/firebase-live-mail-functions.yml", "utf8");
    expect(workflow).not.toContain("sayhi_");
    expect(existsSync("firebase/mail-functions/.env.hi-coworking-plat")).toBe(false);
  });

  it("keeps addresses and keys out of the code", () => {
    for (const source of [triggers, module]) {
      expect(source).not.toMatch(/[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[a-z]{2,}/);
      expect(source).not.toMatch(/re_[A-Za-z0-9]{10,}/);
      expect(source).not.toMatch(/stripe/i);
    }
  });

  it("only shows the preview behind the preview-demo flag", () => {
    const page = readFileSync("apps/web/src/app/account/bookings/page.tsx", "utf8");
    expect(page).toMatch(/SAYHI_PREVIEW_DEMO && isEmailPreview\(search\)/);
  });
});
